def m2_exact() -> list[str]:
    """Infinite-shot energy of each counts-level estimator, readout-only and full noise."""
    rows = [
        r"\begin{tabular}{lcccc}",
        r"\toprule",
        _row(
            "",
            r"\multicolumn{2}{c}{HVA, $\theta=0$ ($-18$)}",
            r"\multicolumn{2}{c}{RVB, $\theta=\VBoundTheta$ (\VMtIdealRvbPt)}",
        ),
        r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}",
        _row("estimator", "readout noise only", "full noise", "readout noise only", "full noise"),
        r"\midrule",
    ]
    for mode, m in EXACT_MODE_KEYS.items():
        cells = [EXACT_MODE_TEX[mode]]
        for a, p in (("Hva", "Zero"), ("Rvb", "Pt")):
            for n in ("Ro", "Full"):
                k = f"Mx{a}{p}{n}{m}"
                cells.append(f"\\V{k}\\,{{\\small(\\V{k}Rel)}}")
        rows.append(_row(*cells))
    rows += [
        r"\midrule",
        _row(
            "kept fraction (symmetry)",
            r"\VMxHvaZeroRoKept",
            r"\VMxHvaZeroFullKept",
            r"\VMxRvbPtRoKept",
            r"\VMxRvbPtFullKept",
        ),
        r"\bottomrule",
        r"\end{tabular}",
    ]
    return rows


def _pm_z(value: str, sem: str, z: str) -> str:
    return f"\\V{value} ${{}}\\pm{{}}$ \\V{sem}\\,{{\\small($z=\\V{z}$)}}"


def m2_seed_check() -> list[str]:
    """The one 2.7-sigma setting rerun with new seeds (quoted numbers)."""
    rows = [
        r"\begin{tabular}{llccc}",
        r"\toprule",
        _row(
            "noise",
            "seed",
            r"row bias (limit \VMxTwHvaZeroFullCtfRel)",
            r"twin (exact \VMbExactTwinHvaFullZero)",
            r"target (exact \VMbExactTargetHvaFullZero)",
        ),
        r"\midrule",
    ]
    for n, label in (("Full", "full"), ("Gt", "gates only")):
        for seed in ("A", "B"):
            k = f"{n}{seed}"
            rows.append(
                _row(
                    label,
                    f"\\VMqSeed{seed}",
                    f"\\VMqRow{k} ${{}}\\pm{{}}$ \\VMqRowSem{k}",
                    _pm_z(f"MqTwin{k}", f"MqTwinSem{k}", f"MqTwinZ{k}"),
                    _pm_z(f"MqTarget{k}", f"MqTargetSem{k}", f"MqTargetZ{k}"),
                )
            )
    rows += [r"\bottomrule", r"\end{tabular}"]
    return rows


def write_all(reg: Registry) -> list[Path]:
    """Write every table."""
    return [
        _write("circuit_stats", circuit_stats()),
        _write("noise_floor", noise_floor()),
        _write("m0_noisy", m0_noisy()),
        _write("m0_statevector", m0_statevector()),
        _write("m1_gradients", m1_gradients(reg)),
        _write("m2_stacks", m2_stacks()),
        _write("m2_vqe", m2_vqe()),
        _write("m2_exact", m2_exact()),
        _write("m2b_sources", m2b_sources()),
        _write("m2b_errors", m2b_errors()),
        _write("m2b_vqe", m2_vqe("Mw")),
        _write("m2_twin", m2_twin()),
        _write("m2_twin_bias", m2_twin_bias()),
        _write("m2_twin_split", m2_twin_split()),
        _write("m2_seed_check", m2_seed_check()),
    ]
