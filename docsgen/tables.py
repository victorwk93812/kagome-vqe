r"""LaTeX tables (booktabs) built from the number registry.

Each table body references ``\V<key>`` macros from ``numbers.tex`` rather than literal values,
so a regenerated registry updates every table and every sentence that quotes the same number.
"""

from __future__ import annotations

from pathlib import Path

from docsgen.numbers import ANSATZ_KEYS, COMBO_KEYS, METHOD_KEYS, METHODS, Registry
from docsgen.paths import REPORT_TABLES

__all__ = ["write_all"]

COMBO_TEX = {
    "hva_spsa": "HVA + SPSA",
    "hva_adam": "HVA + ADAM",
    "rvb_spsa": "RVB + SPSA",
    "rvb_adam": "RVB + ADAM",
}
METHOD_TEX = {
    "adam_forward": "ADAM, forward differences (paper)",
    "adam_central": "ADAM, central differences",
    "adam_spsa": "ADAM, SPSA gradient (hybrid)",
    "adam_parameter_shift": "ADAM, parameter shift",
    "spsa": "plain SPSA",
}


def _row(*cells: str) -> str:
    r"""One tabular row: cells joined by ``&`` and closed by ``\\``."""
    return " & ".join(cells) + r" \\"


def _write(name: str, lines: list[str]) -> Path:
    path = REPORT_TABLES / f"{name}.tex"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        "% Generated by `uv run python -m docsgen`; do not edit.\n" + "\n".join(lines) + "\n"
    )
    return path


def circuit_stats() -> list[str]:
    """Parameters, energies per parameter-shift gradient, and transpiled cost per ansatz."""
    rows = [
        r"\begin{tabular}{lcccccc}",
        r"\toprule",
        _row(
            "ansatz",
            "parameters",
            "gate occurrences",
            "PS energies",
            "CX (Guadalupe)",
            "CX (unshared)",
            "depth",
        ),
        r"\midrule",
    ]
    for ansatz, occ in (("hva", r"$2\times 18$"), ("rvb", r"$12$")):
        a = ANSATZ_KEYS[ansatz]
        rows.append(
            _row(
                ansatz.upper(),
                f"\\VParams{a}",
                occ,
                f"\\VPsEnergies{a}",
                f"\\VCx{a}",
                f"\\VCx{a}Unshared",
                f"\\VDepth{a}",
            )
        )
    rows += [r"\bottomrule", r"\end{tabular}"]
    return rows


def noise_floor() -> list[str]:
    """Energy at the exact parameters, one noise channel at a time."""
    rows = [
        r"\begin{tabular}{lccccc}",
        r"\toprule",
        _row(
            "ansatz",
            "noise-free",
            "readout only",
            r"gate + $T_1/T_2$ only",
            "full",
            r"$E_0\, r_{\mathrm{ro}}\, r_{\mathrm{g}}$",
        ),
        r"\midrule",
    ]
    for ansatz in ("hva", "rvb"):
        a = ANSATZ_KEYS[ansatz]
        rows.append(
            _row(
                ansatz.upper(),
                f"\\VFloor{a}Ideal",
                f"\\VFloor{a}Readout",
                f"\\VFloor{a}Gate",
                f"\\VFloor{a}Full",
                f"\\VKeep{a}Product",
            )
        )
    rows += [r"\bottomrule", r"\end{tabular}"]
    return rows


def m0_noisy() -> list[str]:
    """Noisy FakeGuadalupeV2 benchmark before and after M0."""
    rows = [
        r"\begin{tabular}{lccccc}",
        r"\toprule",
        _row(
            "",
            r"\multicolumn{2}{c}{before M0 (no sampling)}",
            r"\multicolumn{3}{c}{after M0 (sampled, re-measured)}",
        ),
        r"\cmidrule(lr){2-3}\cmidrule(lr){4-6}",
        r"combination & final & best of trace & final & best of trace & rel.\ error \\",
        r"\midrule",
    ]
    for combo, c in COMBO_KEYS.items():
        rows.append(
            _row(
                COMBO_TEX[combo],
                f"\\VPreFinal{c}",
                f"\\VPreBest{c}",
                f"\\VPostFinal{c}",
                f"\\VPostBest{c}",
                f"\\VPostErr{c}",
            )
        )
    rows += [r"\bottomrule", r"\end{tabular}"]
    return rows


def m0_statevector() -> list[str]:
    """Exact-simulator benchmark (unchanged by M0, listed for reference)."""
    rows = [
        r"\begin{tabular}{lcc}",
        r"\toprule",
        r"combination & final energy & rel.\ error \\",
        r"\midrule",
    ]
    for combo, c in COMBO_KEYS.items():
        rows.append(f"{COMBO_TEX[combo]} & \\VSvFinal{c} & \\VSvErr{c} \\\\")
    rows += [r"\bottomrule", r"\end{tabular}"]
    return rows


def m1_gradients(reg: Registry) -> list[str]:
    """Noise-free error of the final parameters per gradient method, equal shots per iteration."""
    rows = [
        r"\begin{tabular}{llccccc}",
        r"\toprule",
        _row(
            "",
            "",
            "",
            r"\multicolumn{2}{c}{gradient noise per component}",
            r"\multicolumn{2}{c}{noise-free error of final parameters}",
        ),
        r"\cmidrule(lr){4-5}\cmidrule(lr){6-7}",
        _row(
            "ansatz",
            "method",
            "$m$",
            r"fixed shots ($\sigma$)",
            r"equal budget ($\sigma_B$)",
            r"shot noise (\VMSeeds{} seeds)",
            "device noise (1 seed)",
        ),
        r"\midrule",
    ]
    for ansatz in ("hva", "rvb"):
        a = ANSATZ_KEYS[ansatz]
        for i, method in enumerate(METHODS):
            m = METHOD_KEYS[method]
            fixed = {"Fwd": r"\VSigmaFwd", "Cen": r"\VSigmaCen", "Ps": f"\\VSigmaPs{a}"}.get(
                m, "--"
            )
            budget = f"\\VBudget{m}{a}" if m in ("Fwd", "Cen", "Ps") else "--"
            noisy = f"\\VMNoisy{a}{m}" if f"MNoisy{a}{m}" in reg else "not run"
            label = ansatz.upper() if i == 0 else ""
            rows.append(
                f"{label} & {METHOD_TEX[method]} & \\VMEnergies{a}{m} & {fixed} & {budget} & "
                f"\\VMIdeal{a}{m} $\\pm$ \\VMIdeal{a}{m}Sd & {noisy} \\\\"
            )
        if ansatz == "hva":
            rows.append(r"\midrule")
    rows += [r"\bottomrule", r"\end{tabular}"]
    return rows


def write_all(reg: Registry) -> list[Path]:
    """Write every table."""
    return [
        _write("circuit_stats", circuit_stats()),
        _write("noise_floor", noise_floor()),
        _write("m0_noisy", m0_noisy()),
        _write("m0_statevector", m0_statevector()),
        _write("m1_gradients", m1_gradients(reg)),
    ]
