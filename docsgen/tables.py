def m1_gradients(reg: Registry) -> list[str]:
    """Noise-free error of the final parameters per gradient method, equal shots per iteration."""
    rows = [
        r"\begin{tabular}{llccccc}",
        r"\toprule",
        _row(
            "",
            "",
            "",
            r"\multicolumn{2}{c}{gradient noise per component}",
            r"\multicolumn{2}{c}{noise-free error of final parameters}",
        ),
        r"\cmidrule(lr){4-5}\cmidrule(lr){6-7}",
        _row(
            "ansatz",
            "method",
            "$m$",
            r"fixed shots ($\sigma$)",
            r"equal budget ($\sigma_B$)",
            r"shot noise (\VMSeeds{} seeds)",
            "device noise (1 seed)",
        ),
        r"\midrule",
    ]
    for ansatz in ("hva", "rvb"):
        a = ANSATZ_KEYS[ansatz]
        for i, method in enumerate(METHODS):
            m = METHOD_KEYS[method]
            fixed = {"Fwd": r"\VSigmaFwd", "Cen": r"\VSigmaCen", "Ps": f"\\VSigmaPs{a}"}.get(
                m, "--"
            )
            budget = f"\\VBudget{m}{a}" if m in ("Fwd", "Cen", "Ps") else "--"
            noisy = f"\\VMNoisy{a}{m}" if f"MNoisy{a}{m}" in reg else "not run"
            label = ansatz.upper() if i == 0 else ""
            rows.append(
                f"{label} & {METHOD_TEX[method]} & \\VMEnergies{a}{m} & {fixed} & {budget} & "
                f"\\VMIdeal{a}{m} ${{}}\\pm{{}}$ \\VMIdeal{a}{m}Sd & {noisy} \\\\"
            )
        if ansatz == "hva":
            rows.append(r"\midrule")
    rows += [r"\bottomrule", r"\end{tabular}"]
    return rows


